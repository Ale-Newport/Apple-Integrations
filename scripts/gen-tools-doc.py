#!/usr/bin/env python3
"""Generates docs/TOOLS.md from the live tool registry.

The registry is the single source of truth for tool names, parameters, types and safety, so the reference is not
written by hand: the running app returns it through `jarvisctl --tools --json`.

Usage:
    scripts/gen-tools-doc.py [--ctl PATH_TO_JARVISCTL] [--input tools.json] [--output docs/TOOLS.md]

With no --input the script runs jarvisctl (the app must be running).
"""
import argparse
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

SECTIONS = [
    ("music", "Apple Music", "AppleScript to the Music app (Automation permission)."),
    ("catalog", "Music catalog", "Public Apple iTunes Search API metadata; not subscription playback."),
    ("reminders", "Reminders", "EventKit (Reminders full access)."),
    ("notes", "Notes", "AppleScript to the Notes app (Automation permission)."),
    ("calendar", "Calendar", "EventKit (Calendars full access)."),
    ("clock", "Clock (alarms and timers)", "Apple Shortcuts actions of the Clock app, through shortcuts you create once (see SHORTCUTS_SETUP.md)."),
    ("contacts", "Contacts", "Contacts framework (optional; Contacts permission)."),
    ("weather", "Weather", "Open-Meteo HTTPS API; geocoding by GeoNames; network required."),
    ("utilities", "Utilities", "Local arithmetic, calculus, algebra, statistics, finance and unit conversions; currency quotes use Frankfurter reference rates."),
    ("system", "macOS", "Public AppKit, IOKit, ScreenCaptureKit and fixed system automation; hardware/TCC limits apply."),
    ("files", "Files and Finder", "Foundation, PDFKit, ImageIO and fixed ditto arguments, restricted to approved roots."),
    ("browser", "Safari and Chrome", "Public AppleScript interfaces; fixed DOM reading requires the browser permission."),
    ("mail", "Mail", "Public Mail AppleScript; sending requires recipient, body and attachment review."),
    ("messages", "Messages", "Public Messages AppleScript; drafts are held in the Jarvis session, and sending needs confirmation."),
    ("research", "Web research", "Explicitly configured SearXNG JSON provider."),
    ("workflows", "Approved Shortcuts and Focus", "User-approved installed Shortcuts; no arbitrary shell or invented third-party APIs."),
    ("conditions", "Future weather conditions", "Optional signed launch agent with persisted one-shot jobs and UserNotifications."),
    ("stopwatch", "Jarvis stopwatch", "Private local persisted elapsed time and laps; separate from native Clock."),
    ("jarvis_timers", "Jarvis timers", "Persistent Jarvis notifications; separate from native Clock."),
]

SAFETY = {
    "read_only": "read-only",
    "modifying": "changes something (nothing is deleted)",
    "destructive": "deletes data — always asks first",
}


def load(args) -> list:
    if args.input:
        payload = json.loads(pathlib.Path(args.input).read_text())
    else:
        ctl = args.ctl
        if not ctl:
            candidates = sorted((ROOT / "build/DerivedData/Build/Products").glob("*/Jarvis Apple Integrations.app/Contents/Helpers/jarvisctl"))
            if not candidates:
                sys.exit("jarvisctl not found; build the app first or pass --ctl")
            ctl = str(candidates[0])
        out = subprocess.run([ctl, "--tools", "--json"], capture_output=True, text=True)
        if out.returncode != 0:
            sys.exit(f"jarvisctl failed ({out.returncode}): {out.stderr.strip() or out.stdout.strip()}\nIs the app running?")
        payload = json.loads(out.stdout)
    return payload["data"] if isinstance(payload, dict) else payload


def section_of(tool_name: str) -> str:
    prefix = tool_name.split(".")[0]
    return {"alarms": "clock", "timers": "clock"}.get(prefix, prefix)


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(tools: list) -> str:
    by_section: dict = {}
    for tool in tools:
        by_section.setdefault(section_of(tool["name"]), []).append(tool)

    lines = [
        "# Tool reference",
        "",
        "<!-- Generated by scripts/gen-tools-doc.py from the live tool registry. Do not edit by hand. -->",
        "",
        "Every action Jarvis can perform is a **tool** with a typed schema. The interpreters (the built-in English/Spanish rules,",
        "or an optional AI model) can only produce calls to these tools; every call is validated against the schema before",
        "anything runs. You can call a tool directly with `jarvisctl --tool NAME --args '{...}'` (see [IPC.md](IPC.md)).",
        "",
        "Common conventions:",
        "",
        "* Dates are `yyyy-MM-dd`; date-times are ISO 8601 with an offset (`2026-10-18T18:00:00+01:00`); times are 24-hour `HH:mm`.",
        "* Every tool answers with a status, a human-readable message in your language, structured `data` with real identifiers,",
        "  and a verification result (`verified`, `unverified` with the reason, or `not applicable`).",
        "* Tools that delete data never run without an explicit, single-use confirmation.",
        "",
    ]
    for key, title, how in SECTIONS:
        group = sorted(by_section.get(key, []), key=lambda t: t["name"])
        if not group:
            continue
        lines += [f"## {title}", "", f"_Backend: {how}_", ""]
        for tool in group:
            lines += [f"### `{tool['name']}`", "", f"{tool['description']}", ""]
            lines.append(f"* **Effect:** {SAFETY.get(tool['safety'], tool['safety'])}")
            if tool.get("confirmation_required"):
                lines.append("* **Confirmation:** required (actual scope is reviewed before execution)")
            for constraint in tool.get("constraints", []):
                lines.append(f"* **Constraint:** {constraint}")
            lines.append("")
            params = tool.get("parameters", {})
            if not params:
                lines += ["_No parameters._", ""]
                continue
            lines += ["| Parameter | Type | Required | Description |", "| --- | --- | --- | --- |"]
            for name in sorted(params, key=lambda n: (not params[n]["required"], n)):
                p = params[name]
                description = p["description"]
                if "default" in p:
                    description += f" (default: `{json.dumps(p['default'])}`)"
                lines.append(f"| `{name}` | `{cell(p['type'])}` | {'yes' if p['required'] else 'no'} | {cell(description)} |")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ctl", help="path to jarvisctl")
    parser.add_argument("--input", help="read the tool schema from this JSON file instead of running jarvisctl")
    parser.add_argument("--output", default=str(ROOT / "docs/TOOLS.md"))
    args = parser.parse_args()

    tools = load(args)
    pathlib.Path(args.output).write_text(render(tools))
    print(f"Wrote {args.output} ({len(tools)} tools)")


if __name__ == "__main__":
    main()
